#!/usr/bin/env python3
"""Third-party notices for everything compiled into RetroDrive (LEGAL-009, docs/17).

Builds `src-tauri/resources/THIRD_PARTY_NOTICES.txt` from the same list of shipped
dependencies as the license gate (`check-licenses.py`): every Rust crate in the Windows
build (normal and build dependencies) and every production npm package, each with its
license and the license/notice files from its own package. Identical texts are printed
once with every component that uses them. MPL-2.0 components also get the location of
their source, as MPL-2.0 asks.

Usage:
    python scripts/third-party-notices.py           # write the file
    python scripts/third-party-notices.py --check   # fail if the file is out of date (CI)

This is an engineering control, not legal advice; docs/16 governs.
"""

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src-tauri" / "resources" / "THIRD_PARTY_NOTICES.txt"
NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE", "AUTHORS")

sys.dont_write_bytecode = True  # keep scripts/__pycache__ untouched
spec = importlib.util.spec_from_file_location("check_licenses", ROOT / "scripts" / "check-licenses.py")
gate = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gate)


def license_files(folder):
    """License-like files at the top of a package folder, sorted by name."""
    if not folder or not folder.is_dir():
        return []
    found = []
    for path in sorted(folder.iterdir(), key=lambda p: p.name.lower()):
        upper = path.name.upper()
        if path.is_file() and any(upper.startswith(n) for n in NAMES) and path.stat().st_size < 200_000:
            text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            if text:
                found.append((path.name, text))
    return found


def rust_folders():
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", gate.TARGET, "--locked"],
        cwd=ROOT / "src-tauri", check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout)
    return {(p["name"], p["version"]): Path(p["manifest_path"]).parent for p in metadata["packages"]}


def components():
    folders = rust_folders()
    rows = []
    for ecosystem, name, version, license_expr, source in [*gate.rust_crates(), *gate.npm_packages()]:
        verdict, _ = gate.classify(license_expr)
        folder = folders.get((name, version)) if ecosystem == "rust" else ROOT / "node_modules" / name
        if ecosystem == "rust":
            where = f"https://crates.io/crates/{name}/{version}"
        else:
            where = f"https://www.npmjs.com/package/{name}/v/{version}"
        rows.append({"ecosystem": ecosystem, "name": name, "version": version, "license": license_expr,
                     "verdict": verdict, "source": source or where, "registry": where, "files": license_files(folder)})
    return rows


def render(rows):
    lines = [
        "RetroDrive - third-party notices",
        "=" * 32,
        "",
        "RetroDrive is built with the open-source components listed below. Each is",
        "used under its own license, reproduced in this file from the component's own",
        "package. RetroDrive does not modify them.",
        "",
        "Components under the Mozilla Public License 2.0 (MPL-2.0) are used unmodified;",
        "their source code is available at the locations given for each of them below.",
        "",
        "Data files RetroDrive includes (controller and light gun lists, BIOS file names)",
        "are credited separately in THIRD_PARTY_CONTROLLERS.txt.",
        "",
        "This file is generated by scripts/third-party-notices.py; do not edit it by hand.",
        "",
        "",
        "Components",
        "----------",
        "",
    ]
    width = max(len(f"{r['name']} {r['version']}") for r in rows)
    for r in rows:
        lines.append(f"{(r['name'] + ' ' + r['version']).ljust(width)}  {r['license'] or '(none declared)'}")
    mpl = [r for r in rows if r["verdict"] == "notice"]
    if mpl:
        lines += ["", "", "Source of the MPL-2.0 components", "-" * 32, ""]
        for r in mpl:
            lines.append(f"{r['name']} {r['version']}: {r['registry']} (repository: {r['source']})")

    # Each distinct license text once, with the components that ship it.
    texts = {}
    missing = []
    for r in rows:
        if not r["files"]:
            missing.append(r)
            continue
        for _, text in r["files"]:
            texts.setdefault(text, []).append(f"{r['name']} {r['version']}")
    lines += ["", "", "License texts", "-" * 13]
    for text, users in texts.items():
        lines += ["", "=" * 78, "Used by: " + ", ".join(users), "=" * 78, "", text]
    if missing:
        lines += ["", "", "Components whose package includes no license file", "-" * 50, "",
                  "These are used under the license shown; its standard text is reproduced above",
                  "for another component with the same license.", ""]
        for r in missing:
            lines.append(f"{r['name']} {r['version']}: {r['license']} ({r['source']})")
    return "\n".join(lines) + "\n"


def main():
    rows = components()
    text = render(rows)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/third-party-notices.py")
            return 1
        print(f"Third-party notices are up to date ({len(rows)} components).")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    missing = sum(1 for r in rows if not r["files"])
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(rows)} components, {len(text) // 1024} KB, {missing} without a license file in their package.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
