#!/usr/bin/env python3
"""App looks (ADR-104): every colour in src/style.css is a CSS variable, so the app can
switch between looks (Classic, Galactic, Bridge, Cartoon, Versus, 80s) without touching the layout.

- `src/style.css` keeps its rules; its colours are `var(--c-…)` tokens defined once in
  a `:root` block at the top (the Classic values, exactly as before).
- Other stylesheets listed in EXTRA (Theme Studio's) use the same tokens.
- `src/looks.css` holds the other looks: a generated palette per look (between the
  GENERATED markers; derived from the Classic tokens by the rules below) followed by
  hand-written effects (fonts, starfield, glows, console bars).

Usage:
    python scripts/app-looks.py           # tokenize new raw colours, regenerate palettes
    python scripts/app-looks.py --check   # fail if style.css has raw colours or looks.css is stale (CI)
"""

import colorsys
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STYLE = ROOT / "src" / "style.css"
LOOKS = ROOT / "src" / "looks.css"
# Other app stylesheets whose colours use the same tokens (no token block of their own).
EXTRA = [ROOT / "src" / "theme-studio" / "theme-studio.css"]
TOKENS_START, TOKENS_END = "/* app-looks:tokens */", "/* app-looks:end */"
GEN_START, GEN_END = "/* GENERATED by scripts/app-looks.py: palettes */", "/* GENERATED: end */"
COLOUR = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(?:,\s*[\d.]+\s*)?\)")


def parse(c):
    """(r, g, b, a) from #rgb, #rrggbb, rgb() or rgba()."""
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0
    nums = [x.strip() for x in c[c.index("(") + 1:-1].split(",")]
    return int(nums[0]), int(nums[1]), int(nums[2]), float(nums[3]) if len(nums) > 3 else 1.0


def name(c):
    r, g, b, a = parse(c)
    base = f"--c-{r:02x}{g:02x}{b:02x}"
    return base if a == 1.0 else f"{base}-a{str(a).replace('0.', '').replace('.', '')}"


def css(r, g, b, a):
    r, g, b = (max(0, min(255, round(x))) for x in (r, g, b))
    return f"#{r:02x}{g:02x}{b:02x}" if a == 1.0 else f"rgba({r},{g},{b},{a:g})"


def hls(r, g, b):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    return h * 360, l, s


def rgb(h, l, s):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, max(0, min(1, l)), max(0, min(1, s)))
    return r * 255, g * 255, b * 255


def role(h, l, s):
    """neutral (backgrounds, borders, text), accent (the blues), or status (keep)."""
    if s < 0.12 or (185 <= h <= 240 and (s < 0.5 or l < 0.3)):
        return "neutral"
    if 185 <= h <= 240:
        return "accent"
    return "status"


def galactic(h, l, s, r):
    """Space opera, the empire's side: black and cold steel grey, imperial red accents."""
    if r == "neutral":
        if l < 0.35:
            return rgb(220, l * 0.5, min(s, 0.2) * 0.4)
        return rgb(215, min(1, l * 1.03), min(s, 0.2) * 0.5)
    if r == "accent":
        if l >= 0.7:
            return rgb(2, 0.74, 0.95)     # light red for text on black
        return rgb(356, 0.47, 0.86)       # imperial red
    return rgb(h, l, s)


def bridge(h, l, s, r):
    """Starship console: near-black with a violet tint; orange, lilac and sky accents."""
    if r == "neutral":
        if l < 0.35:
            return rgb(265, l * 0.5, min(s, 0.4) * 0.6)
        return rgb(28, min(1, l * 1.02), min(0.6, s + 0.25) if l > 0.6 else min(s, 0.3))
    if r == "accent":
        if l >= 0.66:
            return rgb(268, 0.78, 0.7)   # lilac
        return rgb(30, 0.58, 0.95)       # orange
    return rgb(h, l, s)


def cartoon(h, l, s, r):
    """Sunny cartoon: a light look. Lightness is flipped (dark panels become cream, light
    text becomes dark ink); blue buttons become sunshine yellow, light blue text deep blue."""
    if r == "neutral":
        if l < 0.01:
            return rgb(222, 0.12, 0.4)   # shadows stay dark ink
        if l < 0.35:
            return rgb(46, min(0.97, 0.98 - l * 0.7), 0.85 if l < 0.2 else 0.45)
        return rgb(222, max(0.08, 0.98 - l * 0.95), 0.45)
    if r == "accent":
        if l >= 0.6:
            return rgb(214, max(0.28, 1 - l), 0.8)   # deep blue
        return rgb(48, 0.56, 1.0)                    # sunshine yellow
    return rgb(h, 1 - l if l > 0.55 or l < 0.25 else l, s)


def versus(h, l, s, r):
    """Arcade fighter: a dark arena with a red tint; red-orange fire and electric yellow."""
    if r == "neutral":
        if l < 0.35:
            return rgb(352, l * 0.6, min(s, 0.4) * 0.8 + 0.12)
        return rgb(30, min(1, l * 1.02), min(s, 0.3) * 0.5)
    if r == "accent":
        if l >= 0.66:
            return rgb(50, 0.66, 1.0)    # electric yellow
        return rgb(12, 0.52, 0.92)       # red-orange
    return rgb(h, l, s)


def eighties(h, l, s, r):
    """80s synthwave, in the colours of RetroDrive's logo: a deep purple-navy night, lavender
    text, hot pink neon for buttons and cyan glow for light accents."""
    if r == "neutral":
        if l < 0.35:
            return rgb(258, l * 0.75 + 0.01, min(0.75, s + 0.35))
        return rgb(285, min(1, l * 1.03), min(0.7, s + 0.3))
    if r == "accent":
        if l >= 0.66:
            return rgb(186, 0.7, 1.0)    # cyan glow
        return rgb(322, 0.56, 1.0)       # hot pink
    return rgb(h, l, s)


LOOKS_RULES = {"galactic": galactic, "bridge": bridge, "cartoon": cartoon, "versus": versus, "eighties": eighties}


def tokenize(style, extra=None):
    """Move raw colours into the :root token block; returns (new css, token map).
    `extra` adds tokens found in the other stylesheets."""
    if TOKENS_START in style:
        head, rest = style.split(TOKENS_START, 1)
        block, body = rest.split(TOKENS_END, 1)
        tokens = dict(re.findall(r"(--c-[\w-]+):([^;]+);", block))
    else:
        head, body, tokens = "", style, {}
    for k, v in (extra or {}).items():
        tokens.setdefault(k, v)
    for c in sorted(set(COLOUR.findall(body)), key=len, reverse=True):
        tokens.setdefault(name(c), css(*parse(c)))
    body = COLOUR.sub(lambda m: f"var({name(m.group(0))})", body)
    block = ":root{" + "".join(f"{k}:{v};" for k, v in sorted(tokens.items())) + "}"
    return head + TOKENS_START + block + TOKENS_END + body, tokens


def palettes(tokens):
    out = []
    for look, rule in LOOKS_RULES.items():
        decls = []
        for k, v in sorted(tokens.items()):
            r, g, b, a = parse(v)
            h, l, s = hls(r, g, b)
            decls.append(f"{k}:{css(*rule(h, l, s, role(h, l, s)), a)};")
        out.append(f":root[data-look=\"{look}\"]{{{''.join(decls)}}}")
    return GEN_START + "\n" + "\n".join(out) + "\n" + GEN_END


def main():
    check = "--check" in sys.argv
    style = STYLE.read_text(encoding="utf-8")
    extras, extra_tokens = [], {}
    for path in EXTRA:
        text = path.read_text(encoding="utf-8")
        for c in COLOUR.findall(text):
            extra_tokens.setdefault(name(c), css(*parse(c)))
        extras.append((path, text, COLOUR.sub(lambda m: f"var({name(m.group(0))})", text)))
    new_style, tokens = tokenize(style, extra_tokens)
    looks = LOOKS.read_text(encoding="utf-8") if LOOKS.exists() else GEN_START + "\n" + GEN_END + "\n"
    start, end = looks.index(GEN_START), looks.index(GEN_END) + len(GEN_END)
    new_looks = looks[:start] + palettes(tokens) + looks[end:]
    if check:
        problems = []
        if new_style != style:
            problems.append("src/style.css has colours outside the token block")
        problems += [f"{p.relative_to(ROOT).as_posix()} has raw colours" for p, old, new in extras if new != old]
        if new_looks != looks:
            problems.append("src/looks.css palettes are out of date")
        if problems:
            sys.exit("App looks: " + "; ".join(problems) + ". Run: python scripts/app-looks.py")
        print(f"App looks: {len(tokens)} colour tokens, {len(LOOKS_RULES)} extra looks, up to date.")
        return
    STYLE.write_text(new_style, encoding="utf-8", newline="")
    for path, old, new in extras:
        path.write_text(new, encoding="utf-8", newline="")
    LOOKS.write_text(new_looks, encoding="utf-8", newline="")
    print(f"App looks: {len(tokens)} colour tokens written; palettes for {', '.join(LOOKS_RULES)}.")


if __name__ == "__main__":
    main()
